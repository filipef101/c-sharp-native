	static readonly byte[] StaleCounter = [78, 80, 67, 49];

	public static void InstallRoot()
	{
#if NATIVEPOC_STALE_CATALOG
		ScreenNav.Shared.Stage("counter", StaleCounter);
#else
		ScreenNav.Shared.Stage("counter", Counter);
#endif
		ScreenNav.Shared.ShowRoot("counter");
	}

	public static void InstallRest()
	{
		ScreenNav.Shared.Stage("packing", Packing);
		ScreenNav.Shared.Stage("settings", Settings);
		ScreenNav.Shared.Stage("trips", Trips);
		ScreenNav.Shared.Stage("trip", Trip);
		ScreenNav.Shared.Stage("kit", Kit);
		ScreenNav.Shared.Stage("web", Web);
	}

	public static void StageKnown(string id)
	{
		switch (id)
		{
			case "counter":
				ScreenNav.Shared.Stage("counter", Counter);
				return;
			case "packing":
				ScreenNav.Shared.Stage("packing", Packing);
				return;
			case "settings":
				ScreenNav.Shared.Stage("settings", Settings);
				return;
			case "trips":
				ScreenNav.Shared.Stage("trips", Trips);
				return;
			case "trip":
				ScreenNav.Shared.Stage("trip", Trip);
				return;
			case "kit":
				ScreenNav.Shared.Stage("kit", Kit);
				return;
			case "web":
				ScreenNav.Shared.Stage("web", Web);
				return;
			default:
				return;
		}
	}

	public static bool ApplyKept(NavCheckpoint nav)
	{
		ArgumentNullException.ThrowIfNull(nav);
		foreach (var screen in nav.Screens)
		{
			if (screen.Program is { Length: > 0 })
				return false;
		}

		foreach (var id in nav.Stack)
			StageKnown(id);
		foreach (var screen in nav.Screens)
			StageKnown(screen.Id);
		ScreenNav.Shared.Restore(nav);
		CompiledScreens.Recall(nav);
		if (ScreenNav.Shared.DropUnresolved() && ScreenNav.Shared.Depth > 0)
			return true;
		InstallRoot();
		return false;
	}

	public static void ApplyCheckpoint(NavCheckpoint nav)
	{
		ArgumentNullException.ThrowIfNull(nav);
		foreach (var id in nav.Stack)
			StageKnown(id);
		foreach (var screen in nav.Screens)
			StageKnown(screen.Id);
		ScreenNav.Shared.Restore(nav);
		CompiledScreens.Recall(nav);
		Log.Info(MainActivity.Tag, "nav-restore depth=" + ScreenNav.Shared.Depth.ToString(System.Globalization.CultureInfo.InvariantCulture));
		if (ScreenNav.Shared.DropUnresolved())
			return;
		Log.Info(MainActivity.Tag, "state-nav unresolved, showing counter");
		InstallRoot();
	}
